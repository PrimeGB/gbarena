STARTING A MATCH
- Do NOT try to join, snipe or interfere with the other team's lobby. Doing so is a disqualification.
- Each captain creates their team's lobby. Both teams load in and start together when staff or the captains say go.
- It is better to wait until the other team has fully loaded in than to rush. Be patient and start on the agreed countdown.
